async function main() {
    console.log("--- SEEDING OFFICIAL QUESTIONS ---");

    // 1. Wipe existing
    console.log("Deleting existing answers...");
    await prisma.answer.deleteMany({});
    console.log("Deleting existing questions...");
    await prisma.question.deleteMany({});

    // 2. Insert new
    console.log("Inserting 11 Official Questions...");
    for (let i = 0; i < OFFICIAL_QUESTIONS.length; i++) {
        const q = OFFICIAL_QUESTIONS[i];
        await prisma.question.create({
            data: {
                text: q.text,
                shortLabel: q.shortLabel,
                order: i + 1,
                answers: {
                    create: q.options.map(opt => ({
                        text: opt.text,
                        score: opt.value
                    }))
                }
            }
        });
        console.log(`Created Q${i + 1}: ${q.shortLabel}`);
    }

    console.log("--- SEED COMPLETE ---");
}

main()
    .catch((e) => {
        console.error(e);
        process.exit(1);
    })
    .finally(async () => {
        await prisma.$disconnect();
    });
